    /** Small scalable toolbar symbols drawn with the current foreground color. */
    private enum ToolbarIcon implements javax.swing.Icon {
        LANGUAGE, CLOCK, PAUSE, RESUME, RANK;

        @Override
        public int getIconWidth() {
            return 20;
        }

        @Override
        public int getIconHeight() {
            return 20;
        }

        @Override
        public void paintIcon(java.awt.Component component, java.awt.Graphics graphics, int x, int y) {
            java.awt.Graphics2D canvas = (java.awt.Graphics2D) graphics.create();
            try {
                canvas.translate(x, y);
                canvas.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING,
                        java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
                canvas.setColor(component.getForeground());
                canvas.setStroke(new java.awt.BasicStroke(1.5f,
                        java.awt.BasicStroke.CAP_ROUND, java.awt.BasicStroke.JOIN_ROUND));
                if (this == PAUSE) {
                    canvas.fillRect(5, 3, 4, 14);
                    canvas.fillRect(12, 3, 4, 14);
                    return;
                }
                if (this == RESUME) {
                    canvas.fillPolygon(new int[] {5, 5, 16}, new int[] {3, 17, 10}, 3);
                    return;
                }
                if (this == RANK) {
                    // Podium: second, first and third place.
                    canvas.fillRect(2, 9, 5, 9);
                    canvas.fillRect(8, 4, 5, 14);
                    canvas.fillRect(14, 12, 5, 6);
                    return;
                }
                canvas.drawOval(2, 2, 16, 16);
                if (this == CLOCK) {
                    canvas.drawLine(10, 5, 10, 10);
                    canvas.drawLine(10, 10, 14, 12);
                } else {
                    canvas.drawOval(6, 2, 8, 16);
                    canvas.drawLine(2, 10, 18, 10);
                    canvas.drawArc(3, 4, 14, 5, 180, 180);
                    canvas.drawArc(3, 11, 14, 5, 0, 180);
                }
            } finally {
                canvas.dispose();
            }
        }
    }

