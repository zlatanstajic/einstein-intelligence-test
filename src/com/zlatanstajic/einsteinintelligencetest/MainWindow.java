    private String[][] readAnswers() {
        String[][] answers = new String[answerComboBoxes.length][];
        for (int row = 0; row < answerComboBoxes.length; row++) {
            answers[row] = new String[answerComboBoxes[row].length];
            for (int house = 0; house < answerComboBoxes[row].length; house++) {
                answers[row][house] = (String) answerComboBoxes[row][house].getSelectedItem();
            }
        }
        return answers;
    }

