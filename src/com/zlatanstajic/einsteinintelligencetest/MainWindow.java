    private void refreshGameControls() {
        boolean running = session.state() == GameSession.State.RUNNING;
        boolean active = running || session.state() == GameSession.State.PAUSED;
        if (!active) {
            gameTimer.stop();
        }
        pauseButton.setEnabled(active);
        updatePauseButton();
        startButton.setEnabled(!active);
        startButton.setForeground(active ? ModernTheme.MUTED : Color.WHITE);
        restartButton.setEnabled(running);
        setInputsEnabled(running);
        updateAttemptLabel();
        updateCheckButton();
        updateGameStatus();
    }

