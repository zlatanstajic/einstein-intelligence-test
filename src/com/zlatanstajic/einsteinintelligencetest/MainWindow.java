    /**
     * Shows the solved message with the solve time and asks for a name for the rank list. Save stores
     * a valid name; an invalid name is asked for again with the typed text kept. Cancel, the close
     * control and Escape store nothing. The finished game, its controls and its clock stay unchanged.
     */
    private void recordWin() {
        long seconds = session.elapsedSeconds();
        long solvedAt = System.currentTimeMillis();
        String prompt = language.text("Enter your name for the rank list:");
        javax.swing.JTextField nameField = new javax.swing.JTextField(24);
        nameField.getAccessibleContext().setAccessibleName(prompt);
        nameField.addAncestorListener(new javax.swing.event.AncestorListener() {
            @Override
            public void ancestorAdded(javax.swing.event.AncestorEvent event) {
                java.awt.Window dialog = javax.swing.SwingUtilities.getWindowAncestor(nameField);
                dialog.addWindowFocusListener(new java.awt.event.WindowAdapter() {
                    @Override
                    public void windowGainedFocus(java.awt.event.WindowEvent focus) {
                        dialog.removeWindowFocusListener(this);
                        // Runs after JOptionPane focuses its initial Save button, which stays the default button.
                        EventQueue.invokeLater(nameField::requestFocusInWindow);
                    }
                });
            }

            @Override
            public void ancestorRemoved(javax.swing.event.AncestorEvent event) {
            }

            @Override
            public void ancestorMoved(javax.swing.event.AncestorEvent event) {
            }
        });
        javax.swing.JLabel promptLabel = new javax.swing.JLabel(prompt);
        promptLabel.setLabelFor(nameField);
        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 1, 0, 6));
        panel.setOpaque(false);
        panel.add(new javax.swing.JLabel(language.text("Congratulations! You have solved Einstein's Intelligence Test! Press Start to play again.")));
        panel.add(new javax.swing.JLabel(language.text("Your time: ") + formatElapsed(seconds)));
        panel.add(promptLabel);
        panel.add(nameField);
        Object[] options = {language.text("Save"), language.text("Cancel")};
        while (JOptionPane.showOptionDialog(this, panel, language.text("Solved"), JOptionPane.DEFAULT_OPTION,
                JOptionPane.INFORMATION_MESSAGE, null, options, options[0]) == 0) {
            String name = WinnerStore.normalizeName(nameField.getText());
            if (name == null) {
                JOptionPane.showMessageDialog(this, language.text("Enter a name of 1 to 40 characters."),
                        language.text("Invalid name"), JOptionPane.WARNING_MESSAGE);
                continue;
            }
            try {
                winnerStore.add(name, seconds, solvedAt);
            } catch (IOException | SQLException ex) {
                LOGGER.log(Level.WARNING, "Could not save the rank list record", ex);
                JOptionPane.showMessageDialog(this, language.text("Your result could not be saved to the rank list."),
                        language.text("Rank List"), JOptionPane.ERROR_MESSAGE);
            }
            return;
        }
    }

    /** Shows every stored winner, fastest first, or a translated error when the list cannot be loaded. */
    private void showRankList() {
        List<WinnerStore.Winner> winners;
        try {
            winners = winnerStore.ranked();
        } catch (IOException | SQLException ex) {
            LOGGER.log(Level.WARNING, "Could not load the rank list", ex);
            JOptionPane.showMessageDialog(this, language.text("The rank list could not be loaded."),
                    language.text("Rank List"), JOptionPane.ERROR_MESSAGE);
            return;
        }
        new RankListDialog(this, language, winners).setVisible(true);
    }

