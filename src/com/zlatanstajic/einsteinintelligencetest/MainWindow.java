    /**
     * Checks the canonical answer grid through GameSession. A wrong answer uses one attempt.
     * A correct answer or the last wrong answer ends the game. Requires a complete grid in a running game.
     */
    private void checkButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkButtonActionPerformed
        GameSession.Result result = session.check(readAnswers());
        if (result == GameSession.Result.UNAVAILABLE || result == GameSession.Result.INCOMPLETE) {
            return;
        }
        refreshGameControls();
        updateElapsedTime();
        if (result == GameSession.Result.SOLVED) {
            recordWin();
        } else if (result == GameSession.Result.EXHAUSTED) {
            JOptionPane.showMessageDialog(this, language.text("Your solution is not correct, and you have no attempts left. Press Start to play again."),
                    language.text("Game over"), JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, language.text("Your solution is not correct. Attempts left: ") + session.remainingAttempts() + ".",
                    language.text("Incorrect solution"), JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_checkButtonActionPerformed

