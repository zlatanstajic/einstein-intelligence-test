    private void updateResponsiveLayout() {
        int requiredWidth = Math.max(1200, solutionPanel.getPreferredSize().width + 468);
        boolean stacked = contentScrollPane.getViewport().getWidth() < requiredWidth;
        if (stackedLayout == null || stackedLayout != stacked) {
            stackedLayout = stacked;
            java.awt.GridBagLayout layout = (java.awt.GridBagLayout) bodyPanel.getLayout();
            java.awt.GridBagConstraints solution = layout.getConstraints(solutionPanel);
            solution.weightx = stacked ? 1 : .65;
            solution.weighty = stacked ? 0 : 1;
            solution.insets = new java.awt.Insets(0, 0, stacked ? 20 : 0, stacked ? 0 : 20);
            layout.setConstraints(solutionPanel, solution);
            java.awt.GridBagConstraints clues = layout.getConstraints(cluesPanel);
            clues.gridx = stacked ? 0 : 1;
            clues.gridy = stacked ? 1 : 0;
            clues.weightx = stacked ? 1 : .35;
            clues.weighty = 1;
            layout.setConstraints(cluesPanel, clues);
            cluesScrollPane.setPreferredSize(new java.awt.Dimension(400, stacked ? 300 : 480));
            bodyPanel.revalidate();
        }
        updateClueText();
    }

    private void updateClueText() {
        if (clueCheckBoxes == null) {
            return;
        }
        int width = Math.max(220, cluesScrollPane.getViewport().getWidth() - 44);
        for (JCheckBox clue : clueCheckBoxes) {
            String english = (String) clue.getClientProperty("englishText");
            if (english == null) {
                english = clue.getText();
                clue.putClientProperty("englishText", english);
            }
            clue.getAccessibleContext().setAccessibleName(language.text(english));
            String text = language.text(english).replace("&", "&amp;").replace("<", "&lt;");
            // Swing's legacy HTML CSS pixels map to 4/3 logical pixels.
            clue.setText("<html><body style='width: " + (width * 3 / 4) + "px'>" + text + "</body></html>");
            clue.setBorder(javax.swing.BorderFactory.createEmptyBorder(8, 6, 8, 6));
            clue.setOpaque(true);
            styleClue(clue);
        }
        clueListPanel.revalidate();
    }

