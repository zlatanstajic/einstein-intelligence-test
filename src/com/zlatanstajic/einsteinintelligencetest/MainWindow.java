    /** Keep canonical values in every model, but reject values used by another house. */
    private <T> void configureAnswerChoices(JComboBox<T> combo, JComboBox<?>[] row) {
        javax.swing.DefaultComboBoxModel<T> model = new javax.swing.DefaultComboBoxModel<T>() {
            private static final long serialVersionUID = 1L;

            @Override
            public void setSelectedItem(Object value) {
                if (isAnswerAvailable(combo, row, value)) {
                    super.setSelectedItem(value);
                }
            }
        };
        for (int index = 0; index < combo.getItemCount(); index++) {
            model.addElement(combo.getItemAt(index));
        }
        combo.setModel(model);
        javax.swing.DefaultListCellRenderer renderer = language.answerRenderer();
        combo.setRenderer((list, value, index, selected, focused) -> {
            java.awt.Component cell = renderer.getListCellRendererComponent(
                    list, value, index, selected, focused);
            cell.setEnabled(combo.isEnabled() && isAnswerAvailable(combo, row, value));
            return cell;
        });
        combo.addActionListener(event -> {
            for (JComboBox<?> peer : row) {
                peer.repaint();
            }
        });
    }

    private boolean isAnswerAvailable(JComboBox<?> combo, JComboBox<?>[] row, Object value) {
        if (value == null || value.equals(combo.getItemAt(0))) {
            return true;
        }
        for (JComboBox<?> peer : row) {
            if (peer != combo && value.equals(peer.getSelectedItem())) {
                return false;
            }
        }
        return true;
    }

    /** Stable partition: unfinished clues first, marked clues below in clue order. */
    private void reorderClues() {
        java.awt.GridBagLayout layout = (java.awt.GridBagLayout) clueListPanel.getLayout();
        int position = 0;
        for (boolean checked : new boolean[] {false, true}) {
            for (JCheckBox clue : clueCheckBoxes) {
                if (clue.isSelected() == checked) {
                    java.awt.GridBagConstraints constraints = layout.getConstraints(clue);
                    constraints.gridy = position;
                    layout.setConstraints(clue, constraints);
                    clueListPanel.setComponentZOrder(clue, position++);
                }
            }
        }
        clueListPanel.revalidate();
        clueListPanel.repaint();
    }

