    private void updateGameStatus() {
        if (statusLabel == null) {
            return;
        }
        String status;
        switch (session.state()) {
            case PAUSED:
                status = "Paused — resume when you are ready";
                break;
            case FINISHED:
                status = session.remainingAttempts() > 0 ? "Puzzle solved — well done!" : "Game over — try again";
                break;
            case RUNNING:
                status = checkButton.isEnabled() ? "All houses filled — ready to check" : "Game in progress";
                break;
            default:
                status = "Ready to play";
                break;
        }
        statusLabel.setText(language.text(status));
        attemptsLabel.setText(language.text("Attempts left") + ": " + session.remainingAttempts());
        statusLabel.getAccessibleContext().setAccessibleName(language.text(status));
    }

